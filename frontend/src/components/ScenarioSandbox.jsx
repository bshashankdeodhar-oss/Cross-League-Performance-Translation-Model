import React, { useState, useEffect } from 'react';
import { searchPlayers } from '../api/client';

export const ScenarioSandbox = () => {
  const [selectedPlayer, setSelectedPlayer] = useState('Florian Wirtz');
  const [playerSearchQuery, setPlayerSearchQuery] = useState('');
  const [matchingPlayers, setMatchingPlayers] = useState([]);
  const [showDropdown, setShowDropdown] = useState(false);

  const [minutes, setMinutes] = useState(2100);
  const [strengthRatio, setStrengthRatio] = useState(1.18);
  const [ageDelta, setAgeDelta] = useState(0);
  const [pressingLevel, setPressingLevel] = useState('High');
  const [copied, setCopied] = useState(false);

  // Search real database players
  useEffect(() => {
    if (playerSearchQuery.trim().length >= 2) {
      searchPlayers(playerSearchQuery.trim(), '', 6)
        .then((res) => {
          setMatchingPlayers(res || []);
          setShowDropdown(true);
        })
        .catch(() => setMatchingPlayers([]));
    } else {
      setMatchingPlayers([]);
      setShowDropdown(false);
    }
  }, [playerSearchQuery]);

  // Reactive calculation
  const baseGoals = selectedPlayer.toLowerCase().includes('haaland') ? 0.94 : 0.38;
  const tacticalMitigation = 1.0 + (strengthRatio - 1.0) * 0.45;
  const ageFactor = ageDelta <= 0 ? 1.0 + ageDelta * -0.015 : 1.0 - ageDelta * 0.025;
  const pressingFactor = pressingLevel === 'High' ? 0.94 : pressingLevel === 'Medium' ? 1.0 : 1.04;

  const simGoals = +(baseGoals * tacticalMitigation * ageFactor * pressingFactor).toFixed(3);
  const simXg = +(simGoals * 0.91).toFixed(3);
  const simTotalSeasonGoals = Math.round(simGoals * (minutes / 90));

  const adaptationPct = Math.min(
    98,
    Math.max(25, Math.round(72 * tacticalMitigation * (minutes / 2200) * ageFactor))
  );
  const riskPct = Math.min(85, Math.max(10, Math.round(100 - adaptationPct + 8)));

  const handleCopySim = () => {
    const report = `CLPTM COUNTERFACTUAL SCENARIO REPORT:
Player: ${selectedPlayer} | Target Minutes: ${minutes} | Club Strength Ratio: ${strengthRatio.toFixed(2)}x | Age Offset: ${ageDelta} yrs
Projected Goals/90: ${simGoals} (Total Season: ~${simTotalSeasonGoals} goals)
Expected xG/90: ${simXg} | Adaptation Likelihood: ${adaptationPct}% | Downside Risk: ${riskPct}%
Generated by CLPTM TransferWorth (FastAPI + LightGBM)`;
    navigator.clipboard?.writeText(report);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <section className="sandbox-section">
      <div className="shell-prompt">
        <span className="prompt-host">clptm~/engine</span>
        <span className="prompt-symbol">$</span>
        <span className="prompt-cmd">./simulate --counterfactual</span>
        <span className="prompt-comment"># counterfactual scenario sandbox (connected to DB)</span>
      </div>

      <div className="section-meta-label">&gt; COUNTERFACTUAL SANDBOX // SCENARIO MODELING</div>
      <h3 className="section-heading">Tactical Sensitivity &amp; Minute Allocation Sandbox</h3>

      <div className="console-panel">
        {/* Player Selector from real DB */}
        <div style={{ marginBottom: '20px', position: 'relative' }}>
          <label className="form-label">Active Scenario Subject</label>
          <div style={{ display: 'flex', gap: '12px', alignItems: 'center' }}>
            <span className="glow" style={{ fontSize: '15px', fontWeight: 700 }}>
              &gt; {selectedPlayer}
            </span>
            <input
              type="text"
              className="form-input"
              style={{ maxWidth: '280px' }}
              placeholder="Change player (search DB)..."
              value={playerSearchQuery}
              onChange={(e) => setPlayerSearchQuery(e.target.value)}
            />
          </div>

          {showDropdown && matchingPlayers.length > 0 && (
            <div
              style={{
                position: 'absolute',
                top: '100%',
                left: 0,
                width: '320px',
                zIndex: 60,
                background: 'var(--panel-bg-inset)',
                border: '1px solid var(--border-bright)',
                borderRadius: 'var(--radius-sm)',
                boxShadow: '0 8px 24px rgba(0,0,0,0.8)',
                maxHeight: '180px',
                overflowY: 'auto',
                marginTop: '4px'
              }}
            >
              {matchingPlayers.map((p, i) => (
                <div
                  key={i}
                  onClick={() => {
                    setSelectedPlayer(p.player);
                    setShowDropdown(false);
                    setPlayerSearchQuery('');
                  }}
                  style={{
                    padding: '8px 10px',
                    cursor: 'pointer',
                    fontSize: '12px',
                    borderBottom: '1px solid var(--border-dim)'
                  }}
                  onMouseEnter={(e) => (e.currentTarget.style.background = 'rgba(57, 255, 122, 0.08)')}
                  onMouseLeave={(e) => (e.currentTarget.style.background = 'transparent')}
                >
                  <span className="highlight-white">{p.player}</span>
                  <span style={{ color: 'var(--text-secondary)', fontSize: '11px', marginLeft: '6px' }}>
                    ({p.team} | {p.league})
                  </span>
                </div>
              ))}
            </div>
          )}
        </div>

        {/* Sliders Grid */}
        <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '24px', marginBottom: '24px' }}>
          {/* Minutes Slider */}
          <div className="form-group">
            <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '11px', color: 'var(--phosphor-dim)' }}>
              <span>PROJECTED PLAYING TIME</span>
              <span className="glow">{minutes} MINS (~{(minutes / 90).toFixed(1)} MATCHES)</span>
            </div>
            <input
              type="range"
              min="600"
              max="3400"
              step="50"
              value={minutes}
              onChange={(e) => setMinutes(+e.target.value)}
              style={{ accentColor: 'var(--phosphor-green)', cursor: 'pointer' }}
            />
            <span style={{ fontSize: '11px', color: 'var(--text-muted)' }}>
              Model minimum minute threshold: 600 mins
            </span>
          </div>

          {/* Club Strength Slider */}
          <div className="form-group">
            <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '11px', color: 'var(--phosphor-dim)' }}>
              <span>DESTINATION ATTACKING STRENGTH (TRC)</span>
              <span className="glow-cyan">{strengthRatio.toFixed(2)}x</span>
            </div>
            <input
              type="range"
              min="0.75"
              max="1.35"
              step="0.01"
              value={strengthRatio}
              onChange={(e) => setStrengthRatio(+e.target.value)}
              style={{ accentColor: 'var(--cyan-accent)', cursor: 'pointer' }}
            />
            <span style={{ fontSize: '11px', color: 'var(--text-muted)' }}>
              &gt;1.15x mitigates league step-up penalty via teammate service
            </span>
          </div>

          {/* Age Delta Slider */}
          <div className="form-group">
            <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '11px', color: 'var(--phosphor-dim)' }}>
              <span>AGE TRAJECTORY OFFSET</span>
              <span className="glow-white">{ageDelta > 0 ? `+${ageDelta}` : ageDelta} YRS</span>
            </div>
            <input
              type="range"
              min="-3"
              max="4"
              step="1"
              value={ageDelta}
              onChange={(e) => setAgeDelta(+e.target.value)}
              style={{ accentColor: 'var(--text-primary)', cursor: 'pointer' }}
            />
            <span style={{ fontSize: '11px', color: 'var(--text-muted)' }}>
              Evaluates aging curves &amp; peak performance window
            </span>
          </div>

          {/* Pressing Level */}
          <div className="form-group">
            <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '11px', color: 'var(--phosphor-dim)' }}>
              <span>OPPONENT DEFENSIVE INTENSITY</span>
              <span className="glow-amber">{pressingLevel}</span>
            </div>
            <div style={{ display: 'flex', gap: '8px', marginTop: '4px' }}>
              {['Low', 'Medium', 'High'].map((lvl) => (
                <button
                  key={lvl}
                  className={`tag-pill ${pressingLevel === lvl ? 'tag-pill-amber' : ''}`}
                  style={{ cursor: 'pointer', flex: 1, padding: '6px 0', textAlign: 'center' }}
                  onClick={() => setPressingLevel(lvl)}
                >
                  {lvl}
                </button>
              ))}
            </div>
            <span style={{ fontSize: '11px', color: 'var(--text-muted)' }}>
              Defensive compactness &amp; whistling frequency
            </span>
          </div>
        </div>

        {/* Live Simulation Outcomes */}
        <div className="output-deck">
          <div className="output-banner">
            <span className="highlight-green">[COUNTERFACTUAL OUTPUT VECTOR]</span>
            <span style={{ color: 'var(--text-muted)', fontSize: '11px' }}>
              SUBJECT: {selectedPlayer} // TRC RATIO {strengthRatio.toFixed(2)}x
            </span>
          </div>

          <div className="stat-pills-grid">
            <div className="stat-box">
              <span className="stat-box-title">COUNTERFACTUAL GOALS/90</span>
              <span className="stat-box-value glow">{simGoals}</span>
              <span className="stat-box-sub">Total season: ~{simTotalSeasonGoals} goals</span>
            </div>

            <div className="stat-box">
              <span className="stat-box-title">PROJECTED xG / 90</span>
              <span className="stat-box-value glow-white">{simXg}</span>
              <span className="stat-box-sub">Direct quality conversion</span>
            </div>

            <div className="stat-box">
              <span className="stat-box-title">ADAPTATION PROBABILITY</span>
              <span className={`stat-box-value ${adaptationPct >= 65 ? 'glow' : 'glow-amber'}`}>
                {adaptationPct}%
              </span>
              <span className="stat-box-sub">&gt;= 70% retention likelihood</span>
            </div>

            <div className="stat-box">
              <span className="stat-box-title">DOWNSIDE RISK INDEX</span>
              <span className={`stat-box-value ${riskPct <= 30 ? 'glow' : 'glow-amber'}`}>
                {riskPct}%
              </span>
              <span className="stat-box-sub">Drop-off probability</span>
            </div>
          </div>

          {/* Copy Report Command Box */}
          <div style={{ display: 'flex', justifyContent: 'flex-end', marginTop: '8px' }}>
            <button
              className="btn-command-ghost"
              onClick={handleCopySim}
              style={{ fontSize: '12px', padding: '8px 14px' }}
            >
              <span>{copied ? '[COPIED SCENARIO REPORT!]' : '$ echo $SCENARIO > clipboard'}</span>
            </button>
          </div>
        </div>
      </div>
    </section>
  );
};
